// ============================================================
// Grid Cell types & builder
// ============================================================
export interface GridCell {
  letter: string;
  row: number;
  col: number;
  entryIds: number[];
  isStart?: boolean;
  cellNumbers: number[];  // support multiple numbers (across + down starting same cell)
}

export type GridMap = Map<string, GridCell>;

export function buildGridMap(entries: CrosswordEntry[]): GridMap {
  const map: GridMap = new Map();
  const key = (r: number, c: number) => `${r},${c}`;

  for (const entry of entries) {
    for (let i = 0; i < entry.word.length; i++) {
      const r = entry.direction === 'across' ? entry.row : entry.row + i;
      const c = entry.direction === 'across' ? entry.col + i : entry.col;
      const k = key(r, c);
      const existing = map.get(k);
      if (existing) {
        existing.entryIds.push(entry.id);
      } else {
        map.set(k, {
          letter: entry.word[i],
          row: r,
          col: c,
          entryIds: [entry.id],
          cellNumbers: [],
        });
      }
    }
    // Mark start cell with entry number
    const sk = key(entry.row, entry.col);
    const sc = map.get(sk);
    if (sc) {
      sc.isStart = true;
      sc.cellNumbers.push(entry.number);
    }
  }

  return map;
}
